// Copy / paste / duplicate and track lock in the app. Run (after npm run build): node scripts/group1-ui.mjs <clip.webm> <out prefix>
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';

const [clip, out] = process.argv.slice(2);
const port = 4196;
const srv = spawn('npx', ['vite', 'preview', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 3000));
const b = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const pg = await b.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
pg.on('pageerror', (e) => errors.push(String(e)));
const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const mainCount = () => pg.evaluate(() => new Promise((res) => { const r = indexedDB.open('editor'); r.onsuccess = () => { const g = r.result.transaction('projects').objectStore('projects').getAll(); g.onsuccess = () => res(g.result[0].tracks[0].clips.length); }; }));
await pg.goto(`http://localhost:${port}/`);
const [fc] = await Promise.all([pg.waitForEvent('filechooser'), pg.getByRole('button', { name: /โปรเจกต์ใหม่/ }).click()]);
await fc.setFiles(clip);
await pg.waitForURL(/#\/edit\//);
await pg.waitForTimeout(2000);
const clipBtn = () => pg.getByRole('button', { name: /^วิดีโอ 1 / });
await clipBtn().click();
await pg.getByRole('button', { name: 'ทำสำเนา', exact: true }).click();
await pg.waitForTimeout(800);
ok((await mainCount()) === 2, 'duplicate adds a second main clip');
await pg.screenshot({ path: `${out}-after-dup.png` });
await pg.getByRole('button', { name: 'คัดลอก', exact: true }).click();
await pg.getByRole('button', { name: 'วาง', exact: true }).first().click();
await pg.waitForTimeout(800);
ok((await mainCount()) === 3, 'copy then paste adds a third');
await pg.keyboard.press('Control+d');
await pg.waitForTimeout(800);
ok((await mainCount()) === 4, 'Ctrl+D duplicates');
await pg.screenshot({ path: `${out}-copy.png` });
await pg.getByRole('button', { name: 'ล็อกแทร็กนี้' }).first().click();
await pg.waitForTimeout(500);
ok(await clipBtn().isDisabled(), 'locked track: its clips cannot be picked');
ok(!(await pg.getByRole('button', { name: 'ทำสำเนา', exact: true }).count()), 'locked track: the clip tools go away');
await pg.screenshot({ path: `${out}-locked.png` });
await pg.getByRole('button', { name: 'ปลดล็อกแทร็กนี้' }).first().click();
await pg.waitForTimeout(300);
ok(!(await clipBtn().isDisabled()), 'unlocked again');
ok(errors.length === 0, 'no page errors ' + errors.join(' | '));
await b.close();
srv.kill();
