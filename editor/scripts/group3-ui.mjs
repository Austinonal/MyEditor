// My presets, and a project exported to a .myedit file then imported back. Run (after npm run build): node scripts/group3-ui.mjs <clip.webm> <out prefix>
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';

const [clip, out] = process.argv.slice(2);
const port = 4198;
const srv = spawn('npx', ['vite', 'preview', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 3000));
const b = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const pg = await b.newPage({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
const errors = [];
pg.on('pageerror', (e) => errors.push(String(e)));
const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const projects = () => pg.evaluate(() => new Promise((res) => { const r = indexedDB.open('editor'); r.onsuccess = () => { const g = r.result.transaction('projects').objectStore('projects').getAll(); g.onsuccess = () => res(g.result); }; }));
await pg.goto(`http://localhost:${port}/`);
const [fc] = await Promise.all([pg.waitForEvent('filechooser'), pg.getByRole('button', { name: /โปรเจกต์ใหม่/ }).click()]);
await fc.setFiles(clip);
await pg.waitForURL(/#\/edit\//);
await pg.waitForTimeout(2000);
await pg.getByRole('button', { name: 'ข้อความ', exact: true }).first().click();
await pg.getByRole('textbox', { name: 'ข้อความ' }).fill('ป้ายของฉัน');
await pg.getByRole('button', { name: 'เทมเพลต', exact: true }).last().click();
await pg.getByRole('button', { name: 'ป้ายราคา' }).click();
await pg.getByRole('button', { name: /บันทึกข้อความนี้เป็นพรีเซ็ต/ }).click();
await pg.waitForTimeout(500);
ok(await pg.getByRole('button', { name: 'ลบพรีเซ็ต ป้ายของฉัน' }).isVisible(), 'preset saved and listed');
await pg.screenshot({ path: `${out}-presets.png` });
await pg.getByRole('button', { name: 'กลับไปหน้าโปรเจกต์' }).click();
await pg.waitForTimeout(1000);
const [before] = await projects();
await pg.getByRole('button', { name: /^จัดการ / }).first().click();
const [dl] = await Promise.all([pg.waitForEvent('download'), pg.getByRole('button', { name: /ส่งออกไฟล์โปรเจกต์/ }).click()]);
const file = `${out}.myedit`;
await dl.saveAs(file);
ok(dl.suggestedFilename().endsWith('.myedit'), 'downloaded ' + dl.suggestedFilename());
await pg.screenshot({ path: `${out}-export.png` });
await pg.getByRole('button', { name: 'เสร็จ' }).first().click();
const [fc2] = await Promise.all([pg.waitForEvent('filechooser'), pg.getByRole('button', { name: /นำเข้าไฟล์โปรเจกต์/ }).click()]);
await fc2.setFiles(file);
await pg.waitForURL((u) => !u.hash.includes(before.id) && u.hash.includes('#/edit/'));
await pg.waitForTimeout(2500);
const all = await projects();
const copy = all.find((q) => q.id !== before.id);
ok(all.length === 2 && copy && JSON.stringify(copy.tracks) === JSON.stringify(before.tracks), 'imported project has the same tracks');
ok(copy && Object.values(copy.assets).every((a) => a.file.startsWith(`media/${copy.id}/`)), 'imported media lives in its own folder');
await pg.screenshot({ path: `${out}-imported.png` });
const [fc3] = await Promise.all([pg.waitForEvent('filechooser'), (await pg.goto(`http://localhost:${port}/`), pg.getByRole('button', { name: /นำเข้าไฟล์โปรเจกต์/ }).click())]);
await fc3.setFiles({ name: 'bad.myedit', mimeType: 'application/octet-stream', buffer: Buffer.from('nope') });
ok(await pg.getByRole('alert').filter({ hasText: 'ไม่ใช่ไฟล์ .myedit' }).waitFor({ timeout: 5000 }).then(() => true, () => false), 'a bad file is refused with a message');
ok(errors.length === 0, 'no page errors ' + errors.join(' | '));
await b.close();
srv.kill();
