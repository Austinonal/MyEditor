// Categorised stickers and the drawing page in the app. Run (after npm run build): node scripts/group2-ui.mjs <clip.webm> <out prefix>
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';

const [clip, out] = process.argv.slice(2);
const port = 4197;
const srv = spawn('npx', ['vite', 'preview', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 3000));
const b = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const pg = await b.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
pg.on('pageerror', (e) => errors.push(String(e)));
const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const project = () => pg.evaluate(() => new Promise((res) => { const r = indexedDB.open('editor'); r.onsuccess = () => { const g = r.result.transaction('projects').objectStore('projects').getAll(); g.onsuccess = () => res(g.result[0]); }; }));
const count = async (kind) => (await project()).tracks.flatMap((t) => t.clips).filter((c) => c.kind === kind).length;
await pg.goto(`http://localhost:${port}/`);
const [fc] = await Promise.all([pg.waitForEvent('filechooser'), pg.getByRole('button', { name: /โปรเจกต์ใหม่/ }).click()]);
await fc.setFiles(clip);
await pg.waitForURL(/#\/edit\//);
await pg.waitForTimeout(2000);
await pg.getByRole('button', { name: 'สติกเกอร์', exact: true }).first().click();
await pg.getByRole('tab', { name: 'สัตว์' }).or(pg.getByRole('button', { name: 'สัตว์', exact: true })).first().click();
await pg.screenshot({ path: `${out}-stickers.png` });
const texts = await count('text');
await pg.getByRole('button', { name: /^สติกเกอร์ / }).first().click();
await pg.waitForTimeout(500);
ok((await count('text')) === texts + 1, 'animal sticker added');
// the sticker sheet stays open after adding, so the draw button is right there
await pg.getByRole('button', { name: /วาดสติกเกอร์เอง/ }).click();
const pad = pg.getByLabel('พื้นที่วาด');
await pad.waitFor();
await pg.waitForTimeout(500);
await pg.screenshot({ path: `${out}-open.png` });
const box = await pad.boundingBox();
await pg.mouse.move(box.x + box.width * 0.2, box.y + box.height * 0.2);
await pg.mouse.down();
for (let a = 0; a <= 36; a++) await pg.mouse.move(box.x + box.width * (0.5 + 0.3 * Math.cos(a / 5.73)), box.y + box.height * (0.5 + 0.3 * Math.sin(a / 5.73)));
await pg.mouse.up();
await pg.getByRole('radio', { name: 'ถังสี' }).click();
await pg.getByRole('button', { name: '#ffcc00' }).click();
await pad.click({ position: { x: box.width / 2, y: box.height / 2 } });
const filled = await pad.evaluate((c) => [...c.getContext('2d').getImageData(256, 256, 1, 1).data]);
ok(filled[0] === 255 && filled[1] === 204 && filled[3] === 255, 'fill bucket paints inside the circle ' + filled);
const corner = await pad.evaluate((c) => c.getContext('2d').getImageData(2, 2, 1, 1).data[3]);
ok(corner === 0, 'outside stays transparent');
await pg.screenshot({ path: `${out}-draw.png` });
await pg.getByRole('button', { name: 'ย้อนกลับ' }).click();
const undone = await pad.evaluate((c) => c.getContext('2d').getImageData(256, 256, 1, 1).data[3]);
ok(undone === 0, 'undo removes the fill');
const before = (await project()).tracks.flatMap((t) => t.clips).length;
await pg.getByRole('button', { name: 'ใช้ภาพนี้' }).click();
await pg.waitForTimeout(1500);
const p = await project();
ok(p.tracks.flatMap((t) => t.clips).length === before + 1 && Object.values(p.assets).some((a) => a.name === 'ภาพวาด.png' && a.kind === 'photo'), 'drawing saved as a picture overlay');
await pg.screenshot({ path: `${out}-drawn.png` });
ok(errors.length === 0, 'no page errors ' + errors.join(' | '));
await b.close();
srv.kill();
